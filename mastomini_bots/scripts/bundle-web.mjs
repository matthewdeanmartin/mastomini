// Turn the admin app's production build (../mastomini_bots_ui/dist) into
// .embuild/web: one gzip file per asset and assets.rs, the table src/web.rs
// includes with `--features bundled-web`.
//
// Only the gzip copy is embedded, to halve the flash it takes: every browser
// accepts gzip. Run by scripts/build-web.sh; never by hand in CI.

import { createHash } from 'node:crypto';
import { mkdirSync, readdirSync, readFileSync, rmSync, statSync, writeFileSync } from 'node:fs';
import { dirname, join, relative } from 'node:path';
import { fileURLToPath } from 'node:url';
import { gzipSync } from 'node:zlib';

const crate = join(dirname(fileURLToPath(import.meta.url)), '..');
const source = join(crate, '..', 'mastomini_bots_ui', 'dist', 'mastomini-bots-ui', 'browser');
const out = join(crate, '.embuild', 'web');

const MIME = {
  html: 'text/html; charset=utf-8',
  js: 'text/javascript; charset=utf-8',
  css: 'text/css; charset=utf-8',
  json: 'application/json',
  txt: 'text/plain; charset=utf-8',
  svg: 'image/svg+xml',
  png: 'image/png',
  ico: 'image/x-icon',
  webmanifest: 'application/manifest+json',
};

function files(dir) {
  return readdirSync(dir).flatMap((name) => {
    const path = join(dir, name);
    return statSync(path).isDirectory() ? files(path) : [path];
  });
}

let found;
try {
  found = files(source).filter((f) => !f.endsWith('.gitkeep'));
} catch {
  console.error(`No build at ${source}. Run: (cd ../mastomini_bots_ui && npm run build)`);
  process.exit(1);
}
if (!found.some((f) => f.endsWith('index.html'))) {
  console.error(`${source} has no index.html`);
  process.exit(1);
}

rmSync(out, { recursive: true, force: true });
mkdirSync(join(out, 'files'), { recursive: true });

const rust = (s) => JSON.stringify(s); // a JSON string is a valid Rust string literal here
let total = 0;
const entries = found.sort().map((file, i) => {
  const name = relative(source, file).split('\\').join('/');
  const ext = name.split('.').pop();
  const mime = MIME[ext];
  if (!mime) {
    console.error(`Unknown file type: ${name}`);
    process.exit(1);
  }
  const gzip = gzipSync(readFileSync(file), { level: 9 });
  total += gzip.length;
  writeFileSync(join(out, 'files', `${i}.gz`), gzip);
  const etag = `"${createHash('sha256').update(gzip).digest('hex').slice(0, 16)}"`;
  // Angular's output hashing puts a content hash in every name but index.html.
  const immutable = name !== 'index.html';
  return `    Asset {
        path: ${rust('/app/' + name)},
        mime: ${rust(mime)},
        gzip: include_bytes!(concat!(env!("CARGO_MANIFEST_DIR"), "/.embuild/web/files/${i}.gz")),
        etag: ${rust(etag)},
        immutable: ${immutable},
    },`;
});

writeFileSync(
  join(out, 'assets.rs'),
  `// Generated by scripts/bundle-web.mjs from mastomini_bots_ui. Do not edit.\n` +
    `static ASSETS: &[Asset] = &[\n${entries.join('\n')}\n];\n`,
);
console.log(`Admin app: ${entries.length} files, ${(total / 1024).toFixed(1)} KiB gzipped -> ${relative(crate, out)}`);
